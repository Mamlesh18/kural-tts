import pytest

from kural_tts.text.numbers_ta import (
    attach_suffix,
    decimal_to_ta,
    digits_to_ta,
    int_to_ta,
)


@pytest.mark.parametrize(
    "n,expected",
    [
        (0, "பூஜ்ஜியம்"),
        (1, "ஒன்று"),
        (9, "ஒன்பது"),
        (10, "பத்து"),
        (11, "பதினொன்று"),
        (12, "பன்னிரண்டு"),
        (15, "பதினைந்து"),
        (19, "பத்தொன்பது"),
        (20, "இருபது"),
        (21, "இருபத்தொன்று"),
        (23, "இருபத்து மூன்று"),
        (25, "இருபத்தைந்து"),
        (26, "இருபத்தாறு"),
        (30, "முப்பது"),
        (44, "நாற்பத்து நான்கு"),
        (50, "ஐம்பது"),
        (90, "தொண்ணூறு"),
        (99, "தொண்ணூற்றொன்பது"),
        (100, "நூறு"),
        (101, "நூற்றொன்று"),
        (110, "நூற்று பத்து"),
        (250, "இருநூற்று ஐம்பது"),
        (300, "முந்நூறு"),
        (499, "நானூற்று தொண்ணூற்றொன்பது"),
        (900, "தொள்ளாயிரம்"),
        (1000, "ஆயிரம்"),
        (1001, "ஆயிரத்தொன்று"),
        (1250, "ஆயிரத்து இருநூற்று ஐம்பது"),
        (2000, "இரண்டாயிரம்"),
        (2026, "இரண்டாயிரத்து இருபத்தாறு"),
        (2499, "இரண்டாயிரத்து நானூற்று தொண்ணூற்றொன்பது"),
        (3000, "மூவாயிரம்"),
        (5000, "ஐந்தாயிரம்"),
        (10000, "பத்தாயிரம்"),
        (11000, "பதினோராயிரம்"),
        (21000, "இருபத்தோராயிரம்"),
        (50000, "ஐம்பதாயிரம்"),
        (100000, "ஒரு லட்சம்"),
        (150000, "ஒரு லட்சத்து ஐம்பதாயிரம்"),
        (250000, "இரண்டு லட்சத்து ஐம்பதாயிரம்"),
        (10000000, "ஒரு கோடி"),
        (12000000, "ஒரு கோடியே இருபது லட்சம்"),
    ],
)
def test_int_to_ta(n, expected):
    assert int_to_ta(n) == expected


def test_digits_and_decimal():
    assert digits_to_ta("044") == "பூஜ்ஜியம் நான்கு நான்கு"
    assert decimal_to_ta("8.5") == "எட்டு புள்ளி ஐந்து"
    assert decimal_to_ta("2,499") == int_to_ta(2499)


@pytest.mark.parametrize(
    "n,suffix,expected",
    [
        (5, "ஆம்", "ஐந்தாம்"),
        (15, "ஆம்", "பதினைந்தாம்"),
        (10, "க்கு", "பத்துக்கு"),
        (2, "ல", "இரண்டுல"),
        (23, "ஆம்", "இருபத்து மூன்றாம்"),
    ],
)
def test_attach_suffix(n, suffix, expected):
    assert attach_suffix(int_to_ta(n), suffix) == expected
